const assert = require('node:assert/strict')
const { createRequire } = require('node:module')
const { mkdirSync } = require('node:fs')
const { chromium } = createRequire(process.cwd() + '/packages/core/package.json')('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  mkdirSync('tests/screenshots', { recursive: true })
  try {
    await page.goto('http://localhost:5173/login?mode=mock')
    await page.getByLabel('Username').fill('pagination-review')
    await page.getByLabel('Password', { exact: false }).fill('mock-only')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByRole('heading', { name: 'A clearer view of quality.' }).waitFor()
    await page.evaluate(async () => {
      const { mockProjects } = await import('/src/lib/api/mock/data.ts')
      const { setSandboxFiles } = await import('/src/lib/api/mock/files.ts')
      const now = new Date().toISOString()
      mockProjects.push({ id: 9876, name: 'Large suite workspace', baseUrl: 'http://todo.invalid', description: '', runCount: 0, systemCount: 0, createdAt: now, updatedAt: now })
      setSandboxFiles(9876, Array.from({ length: 33 }, (_, i) => {
        const title = `Suite ${String(i + 1).padStart(2, '0')}`
        const tests = Array.from({ length: i === 0 ? 35 : 2 }, (_, j) => `TEST "Behaviour ${String(j + 1).padStart(2, '0')}"\n ID case-${j + 1}\nSTEPS\n navigate to "/"\nASSERT\n assert "Tasks" is_visible\n${i === 0 && j === 34 ? 'STEPS\n click "Tasks"\nASSERT\n assert "Tasks" is_visible\n' : ''}`).join('\n')
        return { id: `suite-${i + 1}`, name: `suite-${i + 1}.axtest`, path: `modules/suite-${i + 1}.axtest`, content: `---\ntitle: ${title}\n---\n${tests}`, updatedAt: now }
      }))
    })
    await page.locator('aside').getByRole('link', { name: 'Projects', exact: true }).click()
    await page.getByRole('link', { name: 'Large suite workspace', exact: true }).click()
    await page.getByRole('navigation', { name: 'Project navigation' }).getByRole('link', { name: 'Test suites', exact: true }).click()
    const suiteRegion = page.getByRole('region', { name: 'Suite selection', exact: true })
    const tests = page.getByRole('region', { name: 'Tests in suite', exact: true })
    const suiteNav = page.getByRole('navigation', { name: 'Suite pagination', exact: true })
    const testNav = page.getByRole('navigation', { name: 'Test pagination', exact: true })
    await suiteRegion.getByText('33 suites found', { exact: true }).waitFor()
    assert.equal(await suiteRegion.getByRole('checkbox').count(), 8)
    assert.equal(await tests.getByRole('checkbox').count(), 10)
    assert(await suiteNav.getByRole('button', { name: 'Previous', exact: true }).isDisabled())
    const firstName = tests.getByRole('button', { name: 'Preview test Behaviour 01', exact: true })
    const before = await tests.boundingBox()
    await firstName.click()
    const preview = page.getByRole('dialog', { name: 'Test preview', exact: true })
    await preview.getByRole('heading', { name: 'Actions', exact: true }).waitFor()
    await preview.getByText('Tasks appears', { exact: true }).waitFor()
    assert.equal(await tests.getByLabel('Behaviour 01', { exact: true }).isChecked(), false)
    assert.equal((await tests.boundingBox()).height, before.height)
    await page.keyboard.press('Escape')
    await preview.waitFor({ state: 'detached' })
    assert(await firstName.evaluate(el => document.activeElement === el))
    await tests.getByRole('button', { name: 'Select test page', exact: true }).click()
    await testNav.getByRole('button', { name: 'Next', exact: true }).click()
    assert.equal(await tests.getByRole('checkbox').count(), 10)
    assert.equal(await tests.getByLabel('Behaviour 11', { exact: true }).isChecked(), false)
    await tests.getByRole('button', { name: 'Select test page', exact: true }).click()
    await page.getByText(/20 selected\s*·\s*20 will run/).waitFor()
    assert(await suiteRegion.getByLabel('Select suite Suite 01').evaluate(el => el.indeterminate))
    await suiteRegion.getByLabel('Select suite Suite 01').check()
    await page.getByText(/35 selected\s*·\s*35 will run/).waitFor()
    await suiteRegion.getByRole('button', { name: 'Clear selection', exact: true }).click()
    await suiteRegion.getByRole('button', { name: 'Select page', exact: true }).click()
    await page.getByText(/49 selected\s*·\s*49 will run/).waitFor()
    await suiteNav.getByRole('button', { name: 'Next', exact: true }).click()
    await suiteRegion.getByText('49 selected in suites outside this page. They will still run.', { exact: true }).waitFor()
    assert.equal(await suiteRegion.getByRole('checkbox').count(), 8)
    await suiteRegion.getByRole('button', { name: 'Select page', exact: true }).click()
    await page.getByText(/65 selected\s*·\s*65 will run/).waitFor()
    await suiteNav.getByRole('button', { name: 'Next', exact: true }).click()
    await suiteRegion.getByRole('button', { name: 'Select page', exact: true }).click()
    await suiteNav.getByRole('button', { name: 'Next', exact: true }).click()
    await suiteRegion.getByRole('button', { name: 'Select page', exact: true }).click()
    await page.getByText('Choose up to 30 suites per batch; 32 suites are selected.', { exact: true }).waitFor()
    assert(await page.getByRole('button', { name: 'Run selected', exact: true }).isDisabled())
    await suiteNav.getByRole('button', { name: 'Next', exact: true }).click()
    assert.equal(await suiteRegion.getByRole('checkbox').count(), 1)
    assert(await suiteNav.getByRole('button', { name: 'Next', exact: true }).isDisabled())
    await suiteRegion.getByRole('button', { name: 'Clear selection', exact: true }).click()
    await page.getByLabel('Search suites', { exact: true }).fill('Behaviour 35')
    await suiteRegion.getByText('1 suite found', { exact: true }).waitFor()
    assert.equal(await tests.getByRole('checkbox').count(), 1)
    await suiteRegion.getByRole('button', { name: 'Select page', exact: true }).click()
    await page.getByText(/1 selected\s*·\s*1 will run/).waitFor()
    await tests.getByRole('button', { name: 'Preview test Behaviour 35', exact: true }).click()
    await preview.getByText('This test uses grouped steps. Its source shows the execution order.', { exact: true }).waitFor()
    assert.match(await preview.locator('pre').innerText(), /ASSERT[\s\S]+STEPS/)
    await page.keyboard.press('Escape')
    await page.getByLabel('Search suites', { exact: true }).fill('not-found-anywhere')
    await suiteRegion.getByText('No suites or behaviours match this search.', { exact: true }).waitFor()
    assert.equal(await tests.getByRole('checkbox').count(), 0)
    await page.getByLabel('Search suites', { exact: true }).fill('')
    await suiteRegion.getByRole('button', { name: 'Clear selection', exact: true }).click()
    await testNav.getByRole('button', { name: 'Next', exact: true }).click()
    await tests.getByRole('button', { name: 'Preview test Behaviour 11', exact: true }).click()
    await preview.getByRole('button', { name: 'Edit in editor', exact: true }).click()
    await page.getByRole('region', { name: 'Suite editor context', exact: true }).waitFor()
    assert.equal(new URL(page.url()).searchParams.get('test'), 'Behaviour 11')
    await page.getByRole('link', { name: 'Back to suites', exact: true }).click()
    await testNav.getByText('Page 2 of 4', { exact: true }).waitFor()
    await tests.getByLabel('Behaviour 11', { exact: true }).check()
    await page.getByRole('button', { name: 'Run selected', exact: true }).click()
    await page.getByRole('region', { name: 'Suite results' }).getByRole('status').filter({ hasText: '1/1 passed' }).waitFor()
    await tests.getByRole('button', { name: 'Preview test Behaviour 11', exact: true }).click()
    await preview.getByText('passed', { exact: true }).waitFor()
    await preview.evaluate(element => Promise.all(element.getAnimations().map(animation => animation.finished.catch(() => {}))))
    await page.screenshot({ path: 'tests/screenshots/suite-test-preview.png', fullPage: true })
    await page.keyboard.press('Escape')
    await preview.waitFor({ state: 'detached' })
    await page.setViewportSize({ width: 760, height: 1050 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.screenshot({ path: 'tests/screenshots/suite-pagination-narrow.png', fullPage: true })
    assert.deepEqual(errors, [])
    console.log('PASS 33-suite/35-test pagination, bounded rendering, page-only selection, cross-page preservation, search reset, stable previews, grouped source, keyboard dismissal, editor return and workspace results')
  } catch (error) {
    console.error('At:', page.url(), 'errors:', errors)
    await page.screenshot({ path: 'tests/screenshots/suite-pagination-error.png', fullPage: true })
    throw error
  } finally { await browser.close() }
})().catch(error => { console.error(String(error)); process.exitCode = 1 })
