const assert = require('node:assert/strict')
const { randomBytes } = require('node:crypto')
const { createRequire } = require('node:module')
const { chromium } = createRequire(process.cwd()+'/packages/core/package.json')('playwright')
const { register } = require('./browser_auth.cjs')
const API='http://localhost:5000', WEB='http://localhost:5173'
;(async()=>{
  const browser=await chromium.launch()
  let page,workspace,project
  async function call(method,path,data) {
    const session=await (await page.request.get(API+'/api/auth/session')).json()
    const response=await page.request.fetch(API+path,{method,data,headers:{'X-CSRF-TOKEN':session.csrfToken}})
    assert(response.ok(), `${method} ${path}: ${response.status()}`)
    return response.status()===204 ? null : response.json()
  }
  async function chooseEnvironment(current,next) {
    await page.getByRole('button',{name:current,exact:true}).click()
    await page.getByRole('option',{name:next,exact:true}).click()
  }
  try {
    page=await browser.newPage({viewport:{width:1400,height:950}})
    page.setDefaultTimeout(30000)
    const errors=[];page.on('pageerror',e=>errors.push(e.message))
    await register(page.context(),API)
    workspace=(await call('GET','/api/workspaces'))[0].id
    project=await call('POST',`/api/workspaces/${workspace}/projects`,{name:'Run input reuse verification '+Date.now(),baseUrl:WEB})
    await call('PUT',`/api/projects/${project.id}/environments/staging`,{baseUrl:WEB,useProductionFallback:false})
    const file=await call('POST',`/api/projects/${project.id}/files`,{name:'inputs',folder:'modules'})
    await call('PUT',`/api/projects/${project.id}/files/${file.id}`,{content:'TEST "Reusable target inputs"\n STEPS\n navigate to "/login?mode=api"\n wait for "Username" to appear\n type "{{AXTEST_USERNAME}}" in "Username"\n type "{{AXTEST_PASSWORD}}" in "Password"\n ASSERT\n assert "Username" is_visible'})
    await page.goto(WEB+`/editor?project=${project.id}&file=modules/inputs.axtest&mode=api`)
    await page.locator('.cm-content').waitFor()
    await page.getByRole('button',{name:'Run',exact:true}).click()
    assert.equal(await page.getByLabel('AXTEST_PASSWORD').inputValue(),'')
    const username='target-'+randomBytes(4).toString('hex'), password=randomBytes(20).toString('base64url')
    await page.getByLabel('AXTEST_USERNAME').fill(username)
    const focus=await page.getByLabel('AXTEST_USERNAME').evaluate(element=>{ const style=getComputedStyle(element); return {visible:element.matches(':focus-visible'),outline:style.outlineStyle,shadow:style.boxShadow} })
    assert(focus.visible)
    assert.equal(focus.outline,'none','The custom ring must not be doubled by a global outline.')
    assert.notEqual(focus.shadow,'none','Keyboard focus must remain visible.')
    await page.getByLabel('AXTEST_PASSWORD').fill(password)
    await page.getByRole('checkbox',{name:'Reuse inputs in this tab',exact:true}).check()
    await page.getByRole('button',{name:'Start run',exact:true}).click()
    await page.getByText('1/1 passed',{exact:true}).first().waitFor({timeout:150000})
    await page.getByRole('button',{name:'Run',exact:true}).click()
    assert.equal(await page.getByLabel('AXTEST_USERNAME').inputValue(),username)
    assert.equal(await page.getByLabel('AXTEST_PASSWORD').inputValue(),password)
    assert(await page.getByRole('checkbox',{name:'Reuse inputs in this tab',exact:true}).isChecked())
    assert(!await page.evaluate(secret=>(JSON.stringify(localStorage)+JSON.stringify(sessionStorage)).includes(secret),password))
    await page.getByRole('button',{name:'Cancel run',exact:true}).click()
    await chooseEnvironment('Staging','Production')
    await page.getByRole('button',{name:'Run',exact:true}).click()
    assert.equal(await page.getByLabel('AXTEST_PASSWORD').inputValue(),'','Other environments must not inherit credentials.')
    await page.getByRole('button',{name:'Cancel run',exact:true}).click()
    await chooseEnvironment('Production','Staging')
    await page.getByRole('button',{name:'Run',exact:true}).click()
    assert.equal(await page.getByLabel('AXTEST_PASSWORD').inputValue(),password)
    await page.getByRole('button',{name:'Clear remembered inputs',exact:true}).click()
    assert.equal(await page.getByLabel('AXTEST_PASSWORD').inputValue(),'')
    assert(!await page.getByRole('checkbox',{name:'Reuse inputs in this tab',exact:true}).isChecked())
    await page.getByRole('button',{name:'Cancel run',exact:true}).click()
    await page.reload();await page.locator('.cm-content').waitFor()
    await page.getByRole('button',{name:'Run',exact:true}).click()
    assert.equal(await page.getByLabel('AXTEST_PASSWORD').inputValue(),'')
    assert.deepEqual(errors,[])
    console.log('PASS opt-in credential reuse, environment isolation, clear control, no browser storage, and a single visible focus indicator')
  } finally {
    if(project) { await call('POST',`/api/workspaces/${workspace}/projects/${project.id}/archive`); await call('DELETE',`/api/workspaces/${workspace}/projects/${project.id}`) }
    await browser.close()
  }
})().catch(error=>{console.error(error);process.exitCode=1})
