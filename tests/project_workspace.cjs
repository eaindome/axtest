const assert=require('node:assert/strict')
const {randomBytes}=require('node:crypto')
const {createRequire}=require('node:module')
const {mkdirSync}=require('node:fs')
const {chromium}=createRequire(process.cwd()+'/packages/core/package.json')('playwright')
const {register}=require('./browser_auth.cjs')
const API='http://localhost:5000',WEB='http://localhost:5173'
;(async()=>{
 const browser=await chromium.launch()
 const owner=await browser.newContext({viewport:{width:1440,height:1050}})
 let page,workspace,project,deleted=false
 const errors=[]
 async function call(context,method,path,data,status=200){
  const session=await(await context.request.get(API+'/api/auth/session')).json()
  const response=await context.request.fetch(API+path,{method,data,headers:{'X-CSRF-TOKEN':session.csrfToken}})
  assert.equal(response.status(),status,`${method} ${path}`)
  return status===204?null:response.json()
 }
 try{
  await register(owner,API)
  workspace=(await call(owner,'GET','/api/workspaces'))[0].id
  project=await call(owner,'POST',`/api/workspaces/${workspace}/projects`,{name:'Project workspace '+randomBytes(4).toString('hex'),baseUrl:WEB},201)
  const source='TEST "Public page"\nSTEPS\n navigate to "/login?mode=api"\nASSERT\n assert "Username" is_visible'
  const file=await call(owner,'POST',`/api/projects/${project.id}/files`,{name:'public','folder':'modules'})
  await call(owner,'PUT',`/api/projects/${project.id}/files/${file.id}`,{content:source})
  const startedAt=new Date().toISOString()
  await call(owner,'POST',`/api/projects/${project.id}/runs`,{environment:'production',totalTests:1,passedTests:1,failedTests:0,durationMs:10,startedAt,completedAt:startedAt,results:[{testId:'public',testName:'Public page',status:'passed',durationMs:10,order:0}]},201)
  await call(owner,'DELETE',`/api/workspaces/${workspace}/projects/${project.id}`,undefined,409)
  console.log('PASS API setup and active-project deletion guard')
  page=await owner.newPage();page.on('pageerror',e=>errors.push(e.message))
  await page.goto(WEB+'/dashboard?mode=api')
  await page.getByRole('heading',{name:'A clearer view of quality.'}).waitFor()
  await page.locator('aside').getByRole('link',{name:'Projects',exact:true}).click()
  await page.getByRole('link',{name:project.name,exact:true}).click()
  await page.waitForURL(`**/projects/${project.id}`)
  await page.getByRole('region',{name:'Environment configuration',exact:true}).waitFor()
  const nav=page.getByRole('navigation',{name:'Project navigation'})
  assert.deepEqual(await nav.getByRole('link').allTextContents(),['Configuration','Test suites','Run history'])
  await page.getByRole('button',{name:'Configuration environment',exact:true}).click();await page.getByRole('option',{name:'Local',exact:true}).click()
  await page.getByLabel('Application URL',{exact:false}).fill(WEB)
  await page.getByRole('button',{name:'Save address',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Address saved.'}).waitFor()
  await page.getByRole('button',{name:'Application login',exact:true}).click();await page.getByRole('option',{name:'Login required',exact:true}).click();await page.getByRole('button',{name:'Add account',exact:true}).click()
  await page.getByLabel('Account name',{exact:false}).fill('QA account')
  const privateUsername='target-'+randomBytes(5).toString('hex'),privatePassword=randomBytes(18).toString('base64url')
  await page.getByLabel('Username',{exact:false}).fill(privateUsername)
  await page.getByLabel('Password',{exact:false}).fill(privatePassword)
  await page.getByRole('button',{name:'Save test account',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Test account saved'}).waitFor()
  console.log('PASS environment and account configuration UI')
  const accounts=await call(owner,'GET',`/api/projects/${project.id}/test-accounts`)
  assert.equal(accounts.length,1);assert(!JSON.stringify(accounts).includes(privatePassword))
  const storage=await page.evaluate(()=>JSON.stringify(localStorage));assert(!storage.includes(privatePassword)&&!storage.includes(privateUsername))
  await nav.getByRole('link',{name:'Test suites',exact:true}).click()
  await page.getByRole('region',{name:'Suite selection',exact:true}).waitFor()
  assert.match(await page.getByRole('button',{name:'Environment',exact:true}).innerText(),/Local/)
  assert.match(await page.getByRole('button',{name:'Test account',exact:true}).innerText(),/QA account/)
  await page.getByRole('button',{name:'Configuration',exact:true}).click()
  await page.getByRole('region',{name:'Environment configuration',exact:true}).waitFor()
  await page.getByRole('navigation',{name:'Project navigation'}).getByRole('link',{name:'Run history',exact:true}).click()
  await page.waitForURL(`**/projects/${project.id}/history`)
  await page.getByRole('button').filter({hasText:'Manual Run'}).first().waitFor()
  const history=await call(owner,'GET',`/api/projects/${project.id}/runs`);assert.equal(history.length,1)
  await page.goto(WEB+`/projects/${project.id}`)
  await page.getByRole('region',{name:'Environment configuration',exact:true}).waitFor()
  mkdirSync('tests/screenshots',{recursive:true});await page.screenshot({path:'tests/screenshots/project-configuration.png',fullPage:true})
  await page.getByRole('link',{name:'Projects',exact:true}).last().click()
  const actions=page.getByRole('button',{name:`Actions for ${project.name}`,exact:true})
  await actions.click()
  const menu=page.locator(`#project-actions-${project.id}`)
  assert.deepEqual(await menu.locator('button,a').allTextContents(),['View project details','Edit details','Open project','Archive project'])
  page.once('dialog',dialog=>dialog.accept())
  await menu.getByRole('menuitem',{name:'Archive project',exact:true}).click()
  await page.getByRole('link',{name:project.name,exact:true}).waitFor({state:'hidden'})
  console.log('PASS project configuration, saved-account handoff, history and archive UI')
  const archived=await call(owner,'GET',`/api/workspaces/${workspace}/projects/${project.id}`);assert(archived.archivedAt)
  assert.equal((await call(owner,'GET',`/api/projects/${project.id}/test-accounts`)).length,1)
  assert.equal((await call(owner,'GET',`/api/projects/${project.id}/runs`)).length,1)
  for(const [path,data] of [['file',{fileId:file.id,content:source,environment:'production'}],['batch',{environment:'production',files:[{fileId:file.id}]}],['',{environment:'production',results:[]}]]){
   await call(owner,'POST',`/api/projects/${project.id}/runs${path?'/'+path:''}`,data,409)
  }
  await call(owner,'PUT',`/api/workspaces/${workspace}/projects/${project.id}`,{name:'blocked'},409)
  await call(owner,'PUT',`/api/projects/${project.id}/environments/local`,{baseUrl:WEB},409)
  await page.getByRole('button',{name:'Project status',exact:true}).click();await page.getByRole('option',{name:'Archived projects',exact:true}).click()
  await actions.click();assert.equal(await menu.getByRole('menuitem',{name:'Edit details',exact:true}).isDisabled(),true)
  await menu.getByRole('menuitem',{name:'Open project',exact:true}).click()
  await page.getByRole('region',{name:'Environment configuration',exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'Save address',exact:true}).isDisabled(),true)
  await page.getByRole('navigation',{name:'Project navigation'}).getByRole('link',{name:'Test suites',exact:true}).click()
  await page.getByRole('region',{name:'Suite selection',exact:true}).waitFor()
  await page.getByRole('checkbox',{name:'Select suite modules/public.axtest',exact:true}).check()
  assert.equal(await page.getByRole('button',{name:'Run selected',exact:true}).isDisabled(),true)
  await page.goto(WEB+'/projects');await page.getByRole('button',{name:'Project status',exact:true}).click();await page.getByRole('option',{name:'Archived projects',exact:true}).click();await actions.click();await menu.getByRole('menuitem',{name:'Restore project',exact:true}).click()
  await page.getByRole('link',{name:project.name,exact:true}).waitFor({state:'hidden'});await page.getByRole('button',{name:'Project status',exact:true}).click();await page.getByRole('option',{name:'Active projects',exact:true}).click();await page.getByRole('link',{name:project.name,exact:true}).waitFor()
  assert.equal((await call(owner,'GET',`/api/workspaces/${workspace}/projects/${project.id}`)).archivedAt,null)
  // Nonmembers and viewers cannot change lifecycle state.
  const outsider=await browser.newContext();await register(outsider,API)
  for(const action of ['archive','restore'])await call(outsider,'POST',`/api/workspaces/${workspace}/projects/${project.id}/${action}`,undefined,404)
  const viewer=await browser.newContext();const viewerCredentials=await register(viewer,API)
  await call(owner,'POST',`/api/workspaces/${workspace}/members`,{username:viewerCredentials.username,role:'Viewer'})
  for(const action of ['archive','restore'])await call(viewer,'POST',`/api/workspaces/${workspace}/projects/${project.id}/${action}`,undefined,404)
  await outsider.close();await viewer.close()
  await actions.click();page.once('dialog',dialog=>dialog.accept());await menu.getByRole('menuitem',{name:'Archive project',exact:true}).click();await page.getByRole('link',{name:project.name,exact:true}).waitFor({state:'hidden'})
  await page.getByRole('button',{name:'Project status',exact:true}).click();await page.getByRole('option',{name:'Archived projects',exact:true}).click();await actions.click();page.once('dialog',dialog=>dialog.dismiss());await menu.getByRole('menuitem',{name:'Delete permanently',exact:true}).click();await page.getByRole('link',{name:project.name,exact:true}).waitFor()
  await actions.click();page.once('dialog',dialog=>dialog.accept());await menu.getByRole('menuitem',{name:'Delete permanently',exact:true}).click();await page.getByRole('link',{name:project.name,exact:true}).waitFor({state:'hidden'});deleted=true
  await call(owner,'GET',`/api/workspaces/${workspace}/projects/${project.id}`,undefined,404)
  assert.deepEqual(errors,[])
  console.log('PASS real API project landing/tabs, saved environment/account handoff, credential privacy, archive persistence and all run guards, restore, viewer/tenant isolation, confirmed permanent deletion')
 }catch(error){
  console.error('Project workspace check at:',page?.url())
  if(page) await page.screenshot({path:'tests/screenshots/project-workspace-error.png',fullPage:true}).catch(()=>{})
  throw error
 }finally{
  if(project&&!deleted){try{await call(owner,'POST',`/api/workspaces/${workspace}/projects/${project.id}/archive`,undefined,204);await call(owner,'DELETE',`/api/workspaces/${workspace}/projects/${project.id}`,undefined,204)}catch{console.error('Verification project retained:',project.id)}}
  await browser.close()
 }
})().catch(error=>{console.error(String(error));process.exitCode=1})
