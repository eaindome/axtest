const assert = require('node:assert/strict')
const { createRequire } = require('node:module')
const { mkdirSync } = require('node:fs')
const { chromium } = createRequire(process.cwd() + '/packages/core/package.json')('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } })
  const errors = [], apiCalls = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', req => { if (req.url().startsWith('http://localhost:5000/api/')) apiCalls.push(req.url()) })
  mkdirSync('tests/screenshots', { recursive: true })
  try {
    await page.goto('http://localhost:5173/login?mode=mock')
    await page.getByLabel('Username').fill('result-review')
    await page.getByLabel('Password', { exact: false }).fill('mock-only')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByRole('heading', { name: 'A clearer view of quality.' }).waitFor()
    await page.evaluate(async () => {
      const { mockProjects } = await import('/src/lib/api/mock/data.ts')
      const { setSandboxFiles } = await import('/src/lib/api/mock/files.ts')
      const now = new Date().toISOString()
      mockProjects.push({ id: 9877, name: 'Results review', baseUrl: 'http://todo.invalid', description: '', runCount: 0, systemCount: 0, createdAt: now, updatedAt: now })
      const names = [...Array.from({ length: 12 }, (_, i) => `Case ${String(i + 1).padStart(2, '0')}`), 'Apply discount to student account', 'View discount history', 'Remove applied discount']
      const content = '---\ntitle: Result suite\n---\n' + names.map((name, i) => `TEST "${name}"\n ID case-${i + 1}\nSTEPS\n navigate to "/"\nASSERT\n assert "Tasks" is_visible\n`).join('\n')
      setSandboxFiles(9877, [{ id: 'results-suite', path: 'modules/results.axtest', name: 'results.axtest', content, updatedAt: now }])
    })
    await page.locator('aside').getByRole('link', { name: 'Projects', exact: true }).click()
    await page.getByRole('link', { name: 'Results review', exact: true }).click()
    await page.getByRole('navigation', { name: 'Project navigation' }).getByRole('link', { name: 'Test suites', exact: true }).click()
    await page.getByRole('button', { name: 'Run settings', exact: true }).click()
    const settings = page.getByRole('region', { name: 'Run settings', exact: true })
    assert(await settings.getByRole('checkbox', { name: 'Show browser', exact: true }).isDisabled())
    assert(await settings.getByRole('button', { name: 'Execution speed', exact: true }).isDisabled())
    await page.keyboard.press('Escape')
    await settings.waitFor({ state: 'detached' })
    await page.getByLabel('Select suite Result suite', { exact: true }).check()
    await page.getByRole('button', { name: 'Run selected', exact: true }).click()
    const results = page.getByRole('region', { name: 'Suite results', exact: true })
    const nav = results.getByRole('navigation', { name: 'Result pagination', exact: true })
    const rows = results.locator('[aria-label="Results on this page"] > details')
    await results.getByRole('status').filter({ hasText: '12/15 passed' }).waitFor()
    assert.equal(await rows.count(), 10)
    assert(await nav.getByRole('button', { name: 'Previous', exact: true }).isDisabled())
    await nav.getByRole('button', { name: 'Next', exact: true }).click()
    assert.equal(await rows.count(), 5)
    assert(await nav.getByRole('button', { name: 'Next', exact: true }).isDisabled())
    async function status(name) {
      await results.getByRole('button', { name: 'Result status', exact: true }).click()
      await page.getByRole('option', { name, exact: true }).click()
    }
    await status('Failed')
    assert.equal(await rows.count(), 3)
    await results.getByText('Element not found: "Apply Discount" button', { exact: true }).waitFor()
    await status('Skipped')
    await results.getByText('No results match this search and status.', { exact: true }).waitFor()
    await status('Passed')
    await results.getByRole('searchbox', { name: 'Search results', exact: true }).fill('Case 01')
    assert.equal(await rows.count(), 1)
    await page.getByLabel('Select suite Result suite', { exact: true }).uncheck()
    await results.getByRole('status').filter({ hasText: '12/15 passed' }).waitFor()
    assert.equal(await rows.count(), 1, 'Changing selection must not alter the submitted batch results.')
    await results.getByRole('searchbox', { name: 'Search results', exact: true }).fill('')
    await nav.getByRole('button', { name: 'Next', exact: true }).click()
    assert.equal(await rows.count(), 2)
    await rows.filter({ hasText: 'Case 12' }).locator('summary').click()
    await rows.filter({ hasText: 'Case 12' }).getByRole('button', { name: 'Edit this test', exact: true }).click()
    await page.getByRole('region', { name: 'Suite editor context', exact: true }).waitFor()
    assert.equal(new URL(page.url()).searchParams.get('test'), 'Case 12')
    await page.getByRole('link', { name: 'Back to suites', exact: true }).click()
    await nav.getByText('Page 2 of 2', { exact: true }).waitFor()
    assert.match(await results.getByRole('button', { name: 'Result status', exact: true }).innerText(), /Passed/)
    assert.equal(await rows.count(), 2)
    await results.getByRole('button', { name: 'Rerun failed', exact: true }).click()
    await results.getByRole('status').filter({ hasText: '0/3 passed' }).waitFor()
    assert.match(await results.getByRole('button', { name: 'Result status', exact: true }).innerText(), /All results/)
    assert.equal(await rows.count(), 3)
    await results.scrollIntoViewIfNeeded()
    await page.screenshot({ path: 'tests/screenshots/run-results-pagination.png', fullPage: true })
    await page.setViewportSize({ width: 760, height: 1050 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.equal(apiCalls.length, 0)
    assert.deepEqual(errors, [])
    console.log('PASS 10-result pages, status/search filters, batch totals independent of selection, editor return restoration, rerun filter reset, mock settings isolation and narrow layout')
  } catch (error) {
    console.error('At:', page.url(), 'errors:', errors)
    await page.screenshot({ path: 'tests/screenshots/run-results-pagination-error.png', fullPage: true })
    throw error
  } finally { await browser.close() }
})().catch(error => { console.error(String(error)); process.exitCode = 1 })
