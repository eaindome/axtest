const assert = require('node:assert/strict')
const { createRequire } = require('node:module')
const { mkdirSync } = require('node:fs')
const { chromium } = createRequire(process.cwd() + '/packages/core/package.json')('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  mkdirSync('tests/screenshots', { recursive: true })
  try {
    await page.goto('http://localhost:5173/login?mode=mock')
    await page.getByLabel('Username').fill('history-review')
    await page.getByLabel('Password', { exact: false }).fill('mock-only')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByRole('heading', { name: 'A clearer view of quality.' }).waitFor()
    await page.evaluate(async () => {
      const { mockRuns, mockRunDetail } = await import('/src/lib/api/mock/data.ts')
      mockRuns.splice(0, mockRuns.length, ...Array.from({ length: 23 }, (_, i) => ({
        ...mockRunDetail, id: 800 + i, suiteName: `modules/journey-${i + 1}.axtest`, status: i % 2 ? 'passed' : 'failed',
        environment: i % 2 ? 'local' : 'production', startedAt: new Date(Date.UTC(2026, 10, 1, i)).toISOString(),
        passedTests: i % 2 ? 38 : 35, failedTests: i % 2 ? 0 : 3,
      })))
      Object.assign(mockRunDetail, mockRuns[22])
    })
    await page.locator('aside').getByRole('link', { name: 'Projects', exact: true }).click()
    await page.getByRole('link', { name: 'Students Portal', exact: true }).click()
    await page.getByRole('navigation', { name: 'Project navigation' }).getByRole('link', { name: 'Run history', exact: true }).click()
    const table = page.getByRole('table', { name: 'Past runs' })
    const nav = page.getByRole('navigation', { name: 'Run pagination' })
    await nav.getByText('1–10 of 23 runs', { exact: true }).waitFor()
    await page.evaluate(() => {
      window.breadcrumbChanges = []
      window.breadcrumbObserver = new MutationObserver(() => {
        const breadcrumb = document.querySelector('[aria-label="Project breadcrumb"]')
        if (breadcrumb) window.breadcrumbChanges.push(breadcrumb.textContent)
      })
      window.breadcrumbObserver.observe(document.querySelector('main'), { childList: true, subtree: true, characterData: true })
    })
    for (const tab of ['Configuration', 'Test suites', 'Run history']) {
      await page.getByRole('navigation', { name: 'Project navigation', exact: true }).getByRole('link', { name: tab, exact: true }).click()
      if (tab === 'Configuration') await page.getByRole('heading', { name: 'Configuration', exact: true }).waitFor()
      if (tab === 'Test suites') await page.getByRole('region', { name: 'Suite selection', exact: true }).waitFor()
      if (tab === 'Run history') await nav.waitFor()
    }
    const breadcrumbs = await page.evaluate(() => { window.breadcrumbObserver.disconnect(); return window.breadcrumbChanges })
    assert(breadcrumbs.length > 0 && breadcrumbs.every(text => text.includes('Students Portal')), 'Project identity stays constant while tabs load.')
    const toggle = page.getByRole('button', { name: 'Collapse sidebar', exact: true })
    const currentUrl = page.url()
    await toggle.click()
    await page.getByRole('button', { name: 'Expand sidebar', exact: true }).click()
    assert.equal(page.url(), currentUrl, 'Sidebar toggle changes the panel without navigating.')
    assert.equal(await table.locator('tbody tr').count(), 10)
    assert.match(await table.locator('tbody tr').first().innerText(), /journey-23/)
    await nav.getByRole('button', { name: 'Next', exact: true }).click()
    await nav.getByText('11–20 of 23 runs', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Run status', exact: true }).click()
    await page.getByRole('option', { name: 'Failed', exact: true }).click()
    await nav.getByText('1–10 of 12 runs', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Run environment', exact: true }).click()
    await page.getByRole('option', { name: 'Local', exact: true }).click()
    await table.getByText('No runs match these filters. Try a different suite, status or environment.', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
    await page.getByRole('searchbox', { name: 'Search runs', exact: true }).fill('#822')
    await nav.getByText('1–1 of 1 runs', { exact: true }).waitFor()
    const run = table.getByRole('button').first()
    await run.click()
    const panel = page.getByRole('dialog', { name: 'Run #822', exact: true })
    await panel.getByRole('heading', { name: 'modules/journey-23.axtest', exact: true }).waitFor()
    const results = panel.getByRole('region', { name: 'Test results' })
    assert.match(await results.locator('details').first().innerText(), /Apply discount/)
    assert(await results.locator('details').first().getAttribute('open') !== null)
    await panel.getByText('Failed at:', { exact: false }).first().waitFor()
    await panel.evaluate(el => Promise.all(el.getAnimations().map(a => a.finished.catch(() => {}))))
    await page.screenshot({ path: 'tests/screenshots/run-history-details.png' })
    await page.keyboard.press('Escape')
    await panel.waitFor({ state: 'detached' })
    assert(await run.evaluate(el => el === document.activeElement))
    assert.equal(await page.getByRole('searchbox', { name: 'Search runs' }).inputValue(), '#822')
    await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
    await page.screenshot({ path: 'tests/screenshots/run-history.png' })
    await page.setViewportSize({ width: 760, height: 900 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.screenshot({ path: 'tests/screenshots/run-history-narrow.png' })
    assert.deepEqual(errors, [])
    console.log('PASS run history sorting, bounded pagination, combined filters, search, failure details, keyboard dismissal and narrow layout')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
