const assert = require('node:assert/strict')
const { randomBytes } = require('node:crypto')
const { createRequire } = require('node:module')
const { chromium } = createRequire(process.cwd() + '/packages/core/package.json')('playwright')
const { signIn } = require('./browser_auth.cjs')
const WEB = process.env.AXTEST_TEST_WEB ?? 'http://localhost:5173'
const API = process.env.AXTEST_TEST_API ?? 'http://localhost:5000'
;(async () => {
  const browser = await chromium.launch()
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}})
    page.setDefaultTimeout(30000)
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    const credentials = {username:'authcheck_' + randomBytes(6).toString('hex'),password:randomBytes(18).toString('base64url')}
    await page.goto(WEB + '/register?mode=api')
    await page.getByLabel('Full name').fill('Authentication verification')
    await page.getByLabel('Username').fill(credentials.username)
    await page.getByLabel('Password').fill('short')
    const rejected = page.waitForResponse(r=>r.url()===API+'/api/auth/register' && r.request().method()==='POST')
    await page.getByRole('button',{name:'Create account',exact:true}).click()
    assert.equal((await rejected).status(),400)
    await page.getByLabel('Password').fill(credentials.password)
    await page.getByRole('button',{name:'Create account',exact:true}).click()
    const heading = page.getByRole('heading',{name:'A clearer view of quality.'})
    await heading.waitFor()
    await page.reload(); await heading.waitFor()
    assert.equal(await page.evaluate(()=>localStorage.getItem('api:axtest_token')),null)
    assert(!await page.evaluate(()=>document.cookie.includes('axtest.session')))
    const other = await browser.newPage()
    await signIn(other,WEB,credentials)
    await page.goto(WEB + '/settings')
    await page.getByLabel('Current password').fill(credentials.password)
    const replacement = randomBytes(18).toString('base64url')
    await page.getByLabel('New password',{exact:false}).first().fill(replacement)
    await page.getByLabel('Confirm new password').fill('does-not-match')
    await page.getByRole('button',{name:'Change password',exact:true}).click()
    await page.getByText('The new passwords do not match.').waitFor()
    await page.getByLabel('Confirm new password').fill(replacement)
    await page.getByRole('button',{name:'Change password',exact:true}).click()
    await page.getByText('Password changed. Other sessions have been signed out.').waitFor()
    await other.reload(); await other.getByLabel('Username').waitFor()
    assert(other.url().includes('/login'))
    await page.reload(); await page.getByRole('heading',{name:'Change password'}).waitFor()
    await page.getByRole('button',{name:'Sign out',exact:true}).click()
    await page.getByLabel('Username').waitFor()
    const anonymous = await page.context().request.get(API + '/api/workspaces')
    assert.equal(anonymous.status(),401)
    credentials.password = replacement
    await signIn(page,WEB,credentials)
    assert.deepEqual(errors,[])
    console.log('PASS UI registration validation, username login, refresh restoration, HttpOnly session, password change, other-session revocation, sign-out and new-password login')
  } finally { await browser.close() }
})().catch(error=>{console.error(error);process.exitCode=1})
