const assert = require('node:assert/strict')
const { createRequire } = require('node:module')
const { chromium } = createRequire(process.cwd() + '/packages/core/package.json')('playwright')
const { register } = require('./browser_auth.cjs')
;(async () => {
 const browser = await chromium.launch()
 try {
  const page = await browser.newPage()
  page.setDefaultTimeout(45000)
  const errors=[]; page.on('pageerror',e=>errors.push(e.message))
  await register(page.context(), 'http://localhost:5000')
  await page.goto('http://localhost:5173/login?mode=mock')
  await page.getByLabel('Username').fill('mock-user')
  await page.getByLabel('Password').fill('anything')
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await page.getByRole('heading',{name:'A clearer view of quality.'}).waitFor()
  await page.getByRole('link',{name:'Test Editor',exact:true}).click()
  await page.locator('.cm-content').waitFor()
  await page.locator('.cm-content').click()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('\n# Keep this unsaved change')
  page.once('dialog',dialog=>dialog.dismiss())
  await page.getByRole('switch',{name:'Toggle mock API'}).click()
  assert.equal(await page.evaluate(()=>localStorage.getItem('axtest_mock')),'true')
  assert.match(await page.locator('.cm-content').innerText(),/Keep this unsaved change/)
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('switch',{name:'Toggle mock API'}).click()
  await page.getByRole('heading',{name:'A clearer view of quality.'}).waitFor()
  assert.equal(await page.evaluate(()=>localStorage.getItem('axtest_mock')),'false')
  assert(await page.getByText('Browser verification',{exact:true}).count())
  await page.getByRole('switch',{name:'Toggle mock API'}).click()
  await page.getByRole('heading',{name:'A clearer view of quality.'}).waitFor()
  assert.equal(await page.evaluate(()=>localStorage.getItem('axtest_mock')),'true')
  const isolated=await page.evaluate(()=>!localStorage.getItem('api:axtest_token') && !!localStorage.getItem('mock:axtest_token'))
  assert(isolated)
  assert.deepEqual(errors,[])
  console.log('PASS canceled mode switch preserves unsaved text; accepted switch initializes API; mock session restores with separate identity')
 } finally { await browser.close() }
})().catch(error=>{console.error(error);process.exitCode=1})
