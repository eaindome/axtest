    assert(!page.url().includes('newSuite='))
    await page.getByRole('button', { name: 'Run this suite', exact: true }).click()
    await page.getByText('2/2 passed', { exact: true }).first().waitFor()
    await page.getByRole('button', { name: 'Close results', exact: true }).click()
    await canvas.getByRole('button', { name: /^Results/ }).click()
    await page.getByText('2/2 passed', { exact: true }).first().waitFor()
    await page.screenshot({ path: 'tests/screenshots/editor-layout.png', fullPage: true })
    await page.getByRole('tab', { name: 'Visual', exact: true }).click()
    await page.getByRole('tab', { name: 'Suite settings', exact: true }).click()
    assert.equal(await page.getByLabel('Suite name', { exact: true }).inputValue(), 'Task management')
    assert.equal(await page.getByLabel('Standalone default URL', { exact: true }).isVisible(), false)
    await page.getByText('Advanced file settings', { exact: true }).click()
    await page.getByText('Axtest runs use the environment selected in Run setup. This file default applies when no runner URL is supplied.', { exact: true }).waitFor()
    await page.getByRole('tab', { name: /^Test cases/ }).click()
