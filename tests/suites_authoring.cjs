    await panels.getByRole('button', { name: 'Outline', exact: true }).click()
    await panels.getByRole('button', { name: 'Explorer', exact: true }).click()
    assert.equal(await page.getByRole('region', { name: 'File explorer', exact: true }).count(), 0)
    assert((await canvas.boundingBox()).width > wide)
    await panels.getByRole('button', { name: 'Explorer', exact: true }).click()
