const assert = require('node:assert/strict')
const { createRequire } = require('node:module')
const { mkdirSync } = require('node:fs')
const { chromium } = createRequire(process.cwd() + '/packages/core/package.json')('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1500, height: 1050 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  mkdirSync('tests/screenshots', { recursive: true })
  try {
    await page.goto('http://localhost:5173/login?mode=mock')
    await page.getByLabel('Username').fill('navigation-review')
    await page.getByLabel('Password', { exact: false }).fill('mock-only')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByRole('heading', { name: 'A clearer view of quality.' }).waitFor()
    await page.evaluate(async () => {
      const { mockProjects } = await import('/src/lib/api/mock/data.ts')
      const { setSandboxFiles } = await import('/src/lib/api/mock/files.ts')
      const now = new Date().toISOString()
      mockProjects.push({ id: 9881, name: 'Navigator review', baseUrl: 'http://todo.invalid', description: '', runCount: 0, systemCount: 0, createdAt: now, updatedAt: now })
      const content = '---\ntitle: Large journey\n---\n' + Array.from({ length: 51 }, (_, i) => `TEST "Behaviour ${String(i + 1).padStart(2, '0')}"\n ID behaviour-${i + 1}\nSTEPS\n navigate to "/"\nASSERT\n assert "Tasks" is_visible\n`).join('\n')
      setSandboxFiles(9881, [{ id: 'navigation-suite', path: 'modules/large.axtest', name: 'large.axtest', content, updatedAt: now }])
    })
    await page.locator('aside').getByRole('link', { name: 'Projects', exact: true }).click()
    await page.getByRole('link', { name: 'Navigator review', exact: true }).click()
    await page.getByRole('navigation', { name: 'Project navigation' }).getByRole('link', { name: 'Test suites', exact: true }).click()
    await page.getByRole('searchbox', { name: 'Search suites' }).fill('Behaviour 51')
    await page.getByRole('button', { name: 'Edit test Behaviour 51', exact: true }).click()
    const canvas = page.getByRole('region', { name: 'Test canvas', exact: true })
    const nav = page.getByRole('navigation', { name: 'Behaviour navigation' })
    const name = page.getByLabel('Behaviour name', { exact: true })
    await name.waitFor()
    assert.equal(await name.inputValue(), 'Behaviour 51')
    assert.equal(await canvas.locator('[id^="test-"]').count(), 1)
    assert(await nav.getByRole('button', { name: 'Next', exact: true }).isDisabled())
    await nav.getByRole('button', { name: 'Choose behaviour', exact: true }).click()
    const search = page.getByRole('searchbox', { name: 'Search choose behaviour', exact: true })
    assert(await search.evaluate(el => el === document.activeElement))
    await search.fill('missing behaviour')
    await page.getByText('No behaviours match this search.', { exact: true }).waitFor()
    assert.equal(await name.inputValue(), 'Behaviour 51', 'Searching does not change the open behaviour.')
    await search.fill('Behaviour 09')
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter')
    assert.equal(await name.inputValue(), 'Behaviour 09')
    const scroll = page.getByRole('region', { name: 'Visual authoring canvas', exact: true })
    await scroll.evaluate(el => { el.scrollTop = el.scrollHeight })
    await nav.getByRole('button', { name: 'Next', exact: true }).click()
    assert.equal(await name.inputValue(), 'Behaviour 10')
    assert.equal(await scroll.evaluate(el => el.scrollTop), 0, 'The next behaviour opens at the top of its actions.')
    await nav.getByRole('button', { name: 'Previous', exact: true }).click()
    await name.fill('Renamed behaviour')
    await nav.getByRole('button', { name: 'Next', exact: true }).click()
    await nav.getByRole('button', { name: 'Previous', exact: true }).click()
    assert.equal(await name.inputValue(), 'Renamed behaviour', 'Moving between behaviours preserves unsaved edits.')
    await page.getByRole('button', { name: 'Run this test', exact: true }).click()
    await page.getByText('1/1 passed', { exact: true }).first().waitFor()
    assert.match(await nav.getByRole('button', { name: 'Choose behaviour', exact: true }).innerText(), /Renamed behaviour.*passed/)
    await nav.getByRole('button', { name: 'Add behaviour', exact: true }).click()
    assert.equal(await name.inputValue(), 'New behaviour 52')
    await page.getByRole('button', { name: 'Delete test', exact: true }).click()
    assert.equal(await name.inputValue(), 'Behaviour 51', 'Deleting the last behaviour opens its neighbour.')
    await page.getByRole('tab', { name: 'Code', exact: true }).click()
    const source = await page.evaluate(async () => (await (await import('/src/lib/api/mock/index.ts')).getExplorer(9881)).files[0].content)
    assert.equal((source.match(/^TEST /gm) || []).length, 51)
    assert.match(source, /Renamed behaviour/)
    // CodeMirror renders a viewport of the full document; verify both ends through the editor.
    await page.locator('.cm-content').press('Control+Home')
    await page.locator('.cm-content').getByText('Behaviour 01', { exact: false }).waitFor()
    await page.locator('.cm-content').press('Control+End')
    await page.locator('.cm-content').getByText('Behaviour 51', { exact: false }).waitFor()
    await page.getByRole('tab', { name: 'Visual', exact: true }).click()
    assert.equal(await name.inputValue(), 'Behaviour 51')
    await page.screenshot({ path: 'tests/screenshots/editor-navigation.png' })
    await page.setViewportSize({ width: 760, height: 950 })
    await page.getByRole('navigation', { name: 'Editor panels' }).getByRole('button', { name: 'Explorer', exact: true }).click()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.equal(await name.count(), 1)
    await page.screenshot({ path: 'tests/screenshots/editor-navigation-narrow.png' })
    assert.deepEqual(errors, [])
    console.log('PASS 51-behaviour navigation, exact-test links, keyboard search, unsaved edits, run status, add/delete, complete Code source and compact layout')
  } catch (error) {
    await page.screenshot({ path: 'tests/screenshots/editor-navigation-error.png' })
    console.error('At:', page.url(), 'errors:', errors, 'statuses:', await page.getByRole('status').allTextContents())
    throw error
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
